'use client';

import React, { useState } from 'react';
import { FileCheck, Globe } from 'lucide-react';
import { apiFetch, errorMessage } from '../../lib/api';
import type { DocumentResponse, DocumentType } from '../../lib/types';
import { AiDraftBanner, ErrorBox } from '../ui/common';
import { Button, Card, Field, Input, PageHeader, SectionTitle } from '../ui/kit';
import { PatientPicker } from '../ui/PatientPicker';

interface DocState {
  loading: boolean;
  error: string;
  doc: DocumentResponse | null;
}
const initial: DocState = { loading: false, error: '', doc: null };

const Output: React.FC<{ s: DocState }> = ({ s }) => (
  <>
    <ErrorBox message={s.error} />
    {s.doc && (
      <div className="space-y-3">
        <AiDraftBanner />
        <pre className="whitespace-pre-wrap rounded-lg border border-line bg-surface-muted p-4 font-sans text-sm text-ink">{s.doc.content}</pre>
        <p className="text-sm text-ink-3">{s.doc.disclaimer}</p>
      </div>
    )}
  </>
);

export const CareCoordinatorPortal: React.FC = () => {
  const [patientId, setPatientId] = useState('');
  const [procedure, setProcedure] = useState('');
  const [language, setLanguage] = useState('Spanish');
  const [priorAuth, setPriorAuth] = useState<DocState>(initial);
  const [discharge, setDischarge] = useState<DocState>(initial);

  const generate = async (
    type: DocumentType,
    body: Record<string, unknown>,
    set: React.Dispatch<React.SetStateAction<DocState>>,
  ) => {
    set({ loading: true, error: '', doc: null });
    try {
      const doc = await apiFetch<DocumentResponse>('/ai/documents', { method: 'POST', body: { type, patientId, ...body } });
      set({ loading: false, error: '', doc });
    } catch (e) {
      set({ loading: false, error: errorMessage(e), doc: null });
    }
  };

  return (
    <div className="space-y-6">
      <PageHeader
        title="Care Coordination: Prior Authorization & Discharge Instructions"
        subtitle="Drafts are generated by AI from the patient record and must be reviewed by a clinician before use."
      />

      <Card className="max-w-2xl">
        <PatientPicker value={patientId} onChange={setPatientId} />
      </Card>

      <div className="grid grid-cols-1 gap-6 lg:grid-cols-2">
        <Card className="space-y-4">
          <SectionTitle icon={<FileCheck className="h-5 w-5" />} className="!mb-0">Prior Authorization Draft</SectionTitle>
          <Field label="Procedure *">
            {(id) => <Input id={id} value={procedure} onChange={(e) => setProcedure(e.target.value)} placeholder="e.g. MRI brain without contrast" />}
          </Field>
          <Button
            onClick={() => generate('PRIOR_AUTH', { procedure: procedure.trim() }, setPriorAuth)}
            disabled={!patientId || !procedure.trim() || priorAuth.loading}
            loading={priorAuth.loading}
            className="w-full"
            data-testid="prior-auth-generate"
          >
            {priorAuth.loading ? 'Generating...' : 'Generate prior-auth draft'}
          </Button>
          <div aria-live="polite"><Output s={priorAuth} /></div>
        </Card>

        <Card className="space-y-4">
          <SectionTitle icon={<Globe className="h-5 w-5" />} className="!mb-0">Discharge Instructions Translation</SectionTitle>
          <Field label="Target language *">
            {(id) => <Input id={id} value={language} onChange={(e) => setLanguage(e.target.value)} />}
          </Field>
          <Button
            onClick={() => generate('DISCHARGE_TRANSLATION', { language: language.trim() }, setDischarge)}
            disabled={!patientId || !language.trim() || discharge.loading}
            loading={discharge.loading}
            className="w-full"
            data-testid="discharge-generate"
          >
            {discharge.loading ? 'Generating...' : 'Generate translated instructions'}
          </Button>
          <div aria-live="polite"><Output s={discharge} /></div>
        </Card>
      </div>
    </div>
  );
};
